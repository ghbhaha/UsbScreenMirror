package com.uav.protocol

/**
 * `CLSE` 报文里的「关闭原因」约定值。
 *
 * 为什么放在 `:protocol` 而不是各自模块里写字符串字面量：
 * 这是一个**两端契约** —— 手机端发什么、宿主端就要认什么。写在协议层，
 * 改文案时编译器会同时检查两端，不会出现"一端改了、另一端悄悄失配"。
 *
 * ⚠️ 这些字符串会出现在用户眼前（宿主的状态副行），所以要写成**能直接读给用户看**的话，
 *   不要用 `USER_STOP` 之类的技术标识当正文。
 */
object CloseReason {

    /**
     * 用户在手机端点了「停止投屏」。
     *
     * 宿主收到它要做两件事，缺一不可：
     *  1. 在界面上**把原因留住**（普通进度事件不许覆盖）—— 否则宿主立刻开始自动重连，
     *     几秒内就会把这条原因刷成"CNXN 已发送…"，用户根本看不到自己那一按生效了没有；
     *  2. **继续自动重连**（不要停）—— 手机端用户接下来大概率会点「授予录屏权限」，
     *     那时链路要能立刻接上，所以不能因为"用户主动停"就彻底放弃。
     */
    const val USER_STOP = "用户停止投屏"
}
